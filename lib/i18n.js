export function resolveLang(lang) {
  const value = String(lang || "").toLowerCase();
  if (value.startsWith("en")) return "en";
  if (value.startsWith("ru")) return "ru";
  const nav = (typeof navigator !== "undefined" && navigator.language) || "ru";
  return nav.toLowerCase().startsWith("en") ? "en" : "ru";
}

// Статус и журнал хранятся не текстом, а ключом с переменными: попап переводит их на текущий язык при показе.
// Управляющие символы JSON.stringify экранирует, поэтому вложенные метки не ломают внешнюю.
const OPEN = "";
const MID = "";
const CLOSE = "";
const MARK = /([^]+)([^]*)/g;

export function mark(key, vars = {}) {
  return `${OPEN}${key}${MID}${JSON.stringify(vars)}${CLOSE}`;
}

export function show(lang, text) {
  if (typeof text !== "string" || !text.includes(OPEN)) return text ?? "";
  return text.replace(MARK, (_, key, json) => {
    let vars = {};
    try {
      vars = JSON.parse(json);
    } catch {
      vars = {};
    }
    const ready = {};
    for (const [name, value] of Object.entries(vars)) ready[name] = typeof value === "string" ? show(lang, value) : value;
    return t(lang, key, ready);
  });
}

export function t(lang, key, vars = {}) {
  const pack = PACK[resolveLang(lang)] || PACK.ru;
  let text = pack[key] ?? PACK.ru[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.split(`{${name}}`).join(String(value ?? ""));
  }
  return text;
}
